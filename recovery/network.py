from __future__ import annotations

import asyncio
import time
from dataclasses import asdict, dataclass
from typing import Any

from playwright.async_api import Page, Request, Response


@dataclass
class NetworkEvent:
    sequence: int
    timestamp: float
    kind: str
    method: str
    url: str
    status: int | None = None
    resource_type: str = ""
    action_id: str = ""
    request_headers: dict[str, str] | None = None
    response_headers: dict[str, str] | None = None
    error: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


class NetworkCollector:
    """Bounded browser-network evidence collector.

    It observes traffic generated by the browser. Network data is supporting
    evidence only; it is never converted directly into a Stage 1 requirement.
    """

    def __init__(self, max_events: int = 2000) -> None:
        self.max_events = max_events
        self.events: list[NetworkEvent] = []
        self._sequence = 0
        self._action_id = ""

    def set_action(self, action_id: str) -> None:
        self._action_id = action_id

    def _append(self, event: NetworkEvent) -> None:
        if len(self.events) >= self.max_events:
            self.events.pop(0)
        self._sequence += 1
        event.sequence = self._sequence
        self.events.append(event)

    async def _on_request(self, request: Request) -> None:
        headers = None
        try:
            headers = dict(await request.all_headers())
        except Exception:
            pass
        self._append(NetworkEvent(
            sequence=0, timestamp=time.time(), kind="request",
            method=request.method, url=request.url,
            resource_type=request.resource_type, action_id=self._action_id,
            request_headers=_safe_headers(headers),
        ))

    async def _on_response(self, response: Response) -> None:
        headers = None
        try:
            headers = dict(await response.all_headers())
        except Exception:
            pass
        self._append(NetworkEvent(
            sequence=0, timestamp=time.time(), kind="response",
            method=response.request.method, url=response.url,
            status=response.status, resource_type=response.request.resource_type,
            action_id=self._action_id, response_headers=_safe_headers(headers),
        ))

    async def _on_request_failed(self, request: Request) -> None:
        self._append(NetworkEvent(
            sequence=0, timestamp=time.time(), kind="request_failed",
            method=request.method, url=request.url,
            resource_type=request.resource_type, action_id=self._action_id,
            error=request.failure or "request failed",
        ))

    def attach(self, page: Page) -> None:
        page.on("request", lambda request: asyncio.get_running_loop().create_task(self._on_request(request)))
        page.on("response", lambda response: asyncio.get_running_loop().create_task(self._on_response(response)))
        page.on("requestfailed", lambda request: asyncio.get_running_loop().create_task(self._on_request_failed(request)))

    def snapshot(self) -> list[dict[str, Any]]:
        return [event.to_dict() for event in self.events]

    def correlate_window(self, started_at: float, ended_at: float, action_id: str) -> list[dict[str, Any]]:
        return [
            event.to_dict() for event in self.events
            if event.action_id == action_id and started_at <= event.timestamp <= ended_at
        ]


def _safe_headers(headers: dict[str, str] | None) -> dict[str, str] | None:
    if not headers:
        return None
    sensitive = {"authorization", "cookie", "set-cookie", "x-auth-token"}
    return {key: ("<redacted>" if key.casefold() in sensitive else value[:500])
            for key, value in headers.items()}


def summarize_network(events: list[dict[str, Any]]) -> dict[str, Any]:
    responses = [e for e in events if e.get("kind") == "response"]
    return {
        "requests": sum(e.get("kind") == "request" for e in events),
        "responses": len(responses),
        "api_responses": sum("/api/" in str(e.get("url", "")) or "/rest/" in str(e.get("url", "")) for e in responses),
        "failed_requests": sum(e.get("kind") == "request_failed" for e in events),
        "methods": sorted({str(e.get("method")) for e in events if e.get("method")}),
        "status_codes": sorted({e.get("status") for e in responses if e.get("status") is not None}),
    }
